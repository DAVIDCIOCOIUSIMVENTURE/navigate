export function getEstablishmentName(id: string): string {
  return establishments.find((e) => e.id === id)?.shortName ?? id
}

export function getClassName(id: string): string {
  return classes.find((c) => c.id === id)?.name ?? id
}

export function getLicenseName(id: string | null): string {
  if (!id) return "None"
  const est = establishments.find((e) => e.license.id === id)
  return est?.license.name ?? id
}
